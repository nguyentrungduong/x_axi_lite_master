module axil_ff
    (
    clk,
    D,
    Q
    );

//------------------------------------------------------------------------------
//Parameters
parameter DW = 1'b1;
//------------------------------------------------------------------------------
// Port declarations
input  logic              clk;
input  logic [DW-1:0]	  D;
output logic [DW-1:0]	  Q;
//------------------------------------------------------------------------------
//internal signal

//------------------------------------------------------------------------------
// FF
always @ (posedge clk)
    begin
    Q <= D;
    end

endmodule 

